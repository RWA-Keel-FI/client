// One-off generator: samples a lat/lon dot grid and marks which dots are land (Natural Earth 110m).
// Output: src/pages/globeData.ts  ('0' ocean, '1' coast land, '2' interior land). Re-run with: node scripts/gen-globe.mjs
import { createRequire } from 'node:module'
import { writeFileSync } from 'node:fs'
import { feature } from 'topojson-client'
import { geoContains } from 'd3-geo'

const require = createRequire(import.meta.url)
const topo = require('world-atlas/land-110m.json')
const land = feature(topo, topo.objects.land)

const ROWS = 44
const PER_EQUATOR = 88
const step = 180 / ROWS
const isLand = (lon, lat) => lat > -90 && lat < 90 && geoContains(land, [((lon + 540) % 360) - 180, lat])

const rows = []
for (let i = 0; i < ROWS; i++) {
  const lat = -90 + (i + 0.5) * step
  const n = Math.max(1, Math.round(PER_EQUATOR * Math.cos((lat * Math.PI) / 180)))
  let s = ''
  for (let j = 0; j < n; j++) {
    const lon = -180 + (j + 0.5) * (360 / n)
    if (!isLand(lon, lat)) {
      s += '0'
      continue
    }
    const d = step * 0.9
    const inner = isLand(lon + d, lat) && isLand(lon - d, lat) && isLand(lon, lat + d) && isLand(lon, lat - d)
    s += inner ? '2' : '1'
  }
  rows.push(s)
}
const total = rows.reduce((a, r) => a + r.length, 0)
const land1 = rows.join('').split('').filter((c) => c !== '0').length
writeFileSync(
  new URL('../src/pages/globeData.ts', import.meta.url),
  `// Generated by scripts/gen-globe.mjs from Natural Earth 110m land. Do not edit by hand.\n// One string per latitude row (south to north); one char per dot: 0 ocean, 1 coast, 2 interior land.\nexport const GLOBE_ROWS: readonly string[] = ${JSON.stringify(rows, null, 0)}\n`,
)
console.log('rows', rows.length, 'dots', total, 'land', land1)
